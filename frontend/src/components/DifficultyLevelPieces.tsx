export function DifficultyLevelPieces({ level }: DifficultyLevelPiecesProps) {
  const maskIdPrefix = useId();
  const filledCount = Number(level);

  return (
    <span aria-hidden="true" className="flex">
      {artworks.map((artwork) => {
        const maskId = `${maskIdPrefix}-${artwork.key}`;
        return (
          <svg
            key={artwork.key}
            width={artwork.width}
            height={artwork.height}
            viewBox={`0 0 ${artwork.width} ${artwork.height}`}
            className={artwork.className}
          >
            <defs>
              {/* 継ぎ目を背景色で塗らず抜くことで、カードのホバー色やテーマに関係なく隙間に見せる。 */}
              <mask id={maskId}>
                <rect
                  width={artwork.width}
                  height={artwork.height}
                  fill="#fff"
                />
                <g fill="none" stroke="#000" strokeWidth={artwork.seamGap}>
                  {artwork.seams.map((seam) => (
                    <path key={seam} d={seam} />
                  ))}
                </g>
              </mask>
            </defs>
            <g mask={`url(#${maskId})`}>
              {artwork.cells.map((cell, index) => (
                <path
                  key={cell}
                  d={cell}
                  className={
                    index < filledCount
                      ? "fill-muted-foreground"
                      : "fill-border"
                  }
                />
              ))}
            </g>
          </svg>
        );
      })}
    </span>
  );
}
